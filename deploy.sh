#!/usr/bin/env bash
# Выкатка сайта на боевой сервер vlad-main — весь путь одной командой.
#
# Порядок работы:
#   1. правим содержимое в docs/
#   2. коммитим     git add ... && git commit
#   3. выкатываем   ./deploy.sh
#
# Написан 2026-09-03, чтобы у ВСЕХ сервисов была одна команда выкатки:
# ./deploy.sh в любом проекте делает одно и то же — отправляет закоммиченное,
# дожидается появления кода на сервере и проверяет результат. Не надо помнить,
# у кого вебхук, у кого push прямо на сервер, а у кого pull руками.
#
# ── Чем этот сервис отличается от ботов ────────────────────────────────────
# У сайта на сервере уже работает автодеплой: GitHub дёргает вебхук, приёмник
# запускает /opt/infra/site-autodeploy/deploy.sh, тот делает pull, проверяет
# ответ сайта и САМ ОТКАТЫВАЕТСЯ на прежний коммит, если проверка не прошла.
# Этот механизм мы не трогаем — он полезен и работает без мака.
#
# Поэтому здесь скрипт не деплоит сам, а: отправляет код, ждёт, пока
# автодеплой отработает, и проверяет, что на сервере оказался нужный коммит
# и сайт отвечает. То есть даёт ту же гарантию, что у ботов: команда
# завершилась успешно = на проде проверенная новая версия.
#
# Сборки образа тут нет — сайт статический, контейнер отдаёт файлы с диска.
# Базы нет, копию снимать нечего.
#
# Имена переменных латиницей: bash не поддерживает кириллицу в них.

set -euo pipefail
cd "$(dirname "$0")"

SERVER="vlad-main-vlad"
REMOTE_DIR="/opt/apps/site"
CONTAINER="site"
SITE_URL="https://vladburba.ru/"

echo "════════════════════════════════════════════════════════════"
echo "  Выкатка сайта на БОЕВОЙ сервер: $SERVER:$REMOTE_DIR"
echo "════════════════════════════════════════════════════════════"

# ── 1/6 ─────────────────────────────────────────────────────────────────────
# Грязное дерево — отказ. На сервер уходит только закоммиченное; иначе
# выкатится вчерашняя версия, выглядя при этом свежей.
echo "→ 1/6 проверяю рабочее дерево на маке"
DIRTY="$(git status --porcelain)"
if [ -n "$DIRTY" ]; then
    echo "✗ есть незакоммиченные правки — выкатывать нечего:" >&2
    echo "$DIRTY" >&2
    echo "  сначала: git add <файлы> && git commit" >&2
    exit 1
fi
LOCAL_SHA="$(git rev-parse HEAD)"
echo "  чисто, выкатываю коммит $(git log --oneline -1)"

# ── 2/6 ─────────────────────────────────────────────────────────────────────
# Оба адреса должны быть заведены: origin — канал доставки (его слушает
# вебхук), nas — хранилище истории.
echo "→ 2/6 проверяю адреса отправки"
for remote in nas origin; do
    if ! git remote get-url "$remote" >/dev/null 2>&1; then
        echo "✗ адреса $remote нет. Завести:" >&2
        [ "$remote" = "nas" ] \
            && echo "  git remote add nas vlad@syn:/volume1/homes/vlad/git/landing-page.git" >&2 \
            || echo "  git remote add origin git@github.com:vladburba/landing-page.git" >&2
        exit 1
    fi
    echo "  $remote: $(git remote get-url $remote)"
done

# ── 3/6 ─────────────────────────────────────────────────────────────────────
# Отправка. Push в origin запускает вебхук — дальше сервер работает сам.
echo "→ 3/6 отправляю код в оба хранилища"
git push --quiet nas main
echo "  nas: отправлено"
git push --quiet origin main
echo "  origin: отправлено — вебхук запустил автодеплой на сервере"

# ── 4/6 ─────────────────────────────────────────────────────────────────────
# Ждём в цикле, а не спим вслепую: вебхук доходит за секунды, но сеть
# непредсказуема, а фиксированную паузу не угадать. Сравниваем коммит на
# сервере с локальным — только это доказывает, что код доехал.
echo "→ 4/6 жду, пока автодеплой подтянет код (до 60 секунд)"
ARRIVED="false"
for _ in $(seq 1 20); do
    REMOTE_SHA="$(ssh "$SERVER" "sudo sudo git -C '$REMOTE_DIR' rev-parse HEAD" 2>/dev/null || echo "")"
    if [ "$REMOTE_SHA" = "$LOCAL_SHA" ]; then ARRIVED="true"; break; fi
    sleep 3
done

if [ "$ARRIVED" != "true" ]; then
    echo "✗ код не доехал за минуту." >&2
    echo "  на сервере: ${REMOTE_SHA:0:7}, отправляли: ${LOCAL_SHA:0:7}" >&2
    echo "  вероятно, не сработал вебхук. Запустить выкатку вручную:" >&2
    echo "    ssh $SERVER 'sudo sudo /opt/infra/site-autodeploy/deploy.sh'" >&2
    echo "  журнал автодеплоя: ssh $SERVER 'sudo sudo tail -20 /opt/infra/site-autodeploy/deploy.log'" >&2
    exit 1
fi
echo "  код на сервере: ${REMOTE_SHA:0:7}"

# ── 5/6 ─────────────────────────────────────────────────────────────────────
# Контейнер должен быть не просто запущен, а признан здоровым: у него есть
# встроенная проверка (запрос к nginx изнутри раз в 30 секунд). Бегущий
# контейнер ещё ничего не доказывает — nginx внутри мог не подняться.
echo "→ 5/6 проверяю контейнер"
STATE="$(ssh "$SERVER" "docker inspect -f '{{.State.Status}}' $CONTAINER" 2>/dev/null || echo "unknown")"
HEALTH="$(ssh "$SERVER" "docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}—{{end}}' $CONTAINER" 2>/dev/null || echo "—")"
RESTARTS="$(ssh "$SERVER" "docker inspect -f '{{.RestartCount}}' $CONTAINER" 2>/dev/null || echo "?")"
echo "  статус: $STATE | здоровье: $HEALTH | перезапусков: $RESTARTS"

if [ "$STATE" != "running" ]; then
    echo "✗ контейнер не запущен" >&2
    ssh "$SERVER" "docker logs --tail 30 $CONTAINER" 2>&1 || true
    exit 1
fi

# ── 6/6 ─────────────────────────────────────────────────────────────────────
# Последняя проверка — снаружи, как её увидит посетитель. Всё предыдущее
# могло пройти, а сайт остаться недоступным из-за nginx на хосте или DNS.
echo "→ 6/6 проверяю сайт снаружи"
CODE="$(curl -s -o /dev/null -w '%{http_code}' --max-time 20 "$SITE_URL" || echo "000")"
if [ "$CODE" != "200" ]; then
    echo "✗ сайт отвечает $CODE вместо 200" >&2
    echo "  автодеплой на сервере откатывается сам при провале своей проверки —" >&2
    echo "  посмотреть, что он решил: ssh $SERVER 'sudo sudo tail -20 /opt/infra/site-autodeploy/deploy.log'" >&2
    exit 1
fi
echo "  сайт отвечает $CODE"

echo ""
echo "════════════════════════════════════════════════════════════"
echo "✓ выкачено и проверено"
echo "  коммит:    $(git log --oneline -1)"
echo "  контейнер: $CONTAINER ($HEALTH)"
echo "  сайт:      $SITE_URL — $CODE"
echo ""
echo "  Откат делает автодеплой сам, если сайт не отвечает после выкатки."
echo "  Журнал:    ssh $SERVER 'sudo sudo tail -20 /opt/infra/site-autodeploy/deploy.log'"
echo "════════════════════════════════════════════════════════════"
